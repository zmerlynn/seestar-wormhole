// Legal local completions and finite post-PAUSE DATA, no state-field mutation.
// Every offered flow control is accepted. An empty higher-ID holder must resume
// even while a lower ID keeps crossing its thresholds.
func TestResumeCannotStarve(t *testing.T) {
	cfg := DefaultConfig()
	cfg.HighWater = 100
	d := activeDriver(t, cfg, false)
	a, b := d.open(445), d.open(4700)
	wa := mustAction(t, d.frame(Frame{DataCommand, a.Channel, bytes.Repeat([]byte{'a'}, 101)}), WriteLocal)
	wb := mustAction(t, d.frame(Frame{DataCommand, b.Channel, bytes.Repeat([]byte{'b'}, 101)}), WriteLocal)
	d.auto = false
	send := mustAction(t, d.step(local(Event{Kind: LocalWritten, Count: 101}, wa)), Send)
	d.step(local(Event{Kind: LocalWritten, Count: 101}, wb))
	overtakes := 0
	for i := 0; i < 1024; i++ {
		d.now = d.now.Add(time.Millisecond)
		if send.Data[1] == b.Channel {
			if !bytes.Equal(send.Data, []byte{6, b.Channel, 0, 0}) {
				t.Fatalf("higher channel control=%x", send.Data)
			}
			return
		}
		if send.Data[0] == 6 {
			wa = mustAction(t, d.frame(Frame{DataCommand, a.Channel, bytes.Repeat([]byte{'a'}, 101)}), WriteLocal)
		} else {
			d.step(local(Event{Kind: LocalWritten, Count: 101}, wa))
		}
		send = mustAction(t, d.step(Event{Kind: Sent, Token: send.Token, Count: len(send.Data)}), Send)
		overtakes++
	}
	t.Fatalf("empty channel %d RESUME starved by %d accepted controls for channel %d; next=%x higher=%+v usage=%+v", b.Channel, overtakes, a.Channel, send.Data, d.m.Channel(b.Channel), d.m.Usage())
}

func TestWakeDuringPauseHandoff(t *testing.T) {
	cfg := DefaultConfig()
	cfg.HighWater = 100
	d := activeDriver(t, cfg, false)
	ch := d.open(445)
	d.auto = false
	out := d.frame(Frame{DataCommand, ch.Channel, bytes.Repeat([]byte{'b'}, MaxData)})
	pause := mustAction(t, out, Send)
	w := mustAction(t, out, WriteLocal)
	// Already-admitted bytes arrive and successful writes exceed the exact WAKE
	// threshold before the PAUSE completion. Pressure remains well above low.
	d.frame(Frame{DataCommand, ch.Channel, bytes.Repeat([]byte{'b'}, MaxData)})
	d.frame(Frame{DataCommand, ch.Channel, bytes.Repeat([]byte{'b'}, MaxData)})
	w = mustAction(t, d.step(local(Event{Kind: LocalWritten, Count: MaxData}, w)), WriteLocal)
	d.step(local(Event{Kind: LocalWritten, Count: 5}, w))
	out = d.step(Event{Kind: Sent, Token: pause.Token, Count: 4})
	wake, ok := find(out, Send)
	if !ok || !bytes.Equal(wake.Data, []byte{7, ch.Channel, 0, 0}) {
		t.Fatalf("WAKE generated by 8197-byte drain during PAUSE handoff lost: got Send=%v data=%x state=%+v", ok, wake.Data, d.m.Channel(ch.Channel))
	}
}

func TestDataCannotStarve(t *testing.T) {
	cfg := DefaultConfig()
	cfg.HighWater = 100
	d := activeDriver(t, cfg, false)
	ch := d.open(445)
	w := mustAction(t, d.frame(Frame{DataCommand, ch.Channel, bytes.Repeat([]byte{'a'}, 101)}), WriteLocal)
	d.auto = false
	send := mustAction(t, d.step(local(Event{Kind: LocalWritten, Count: 101}, w)), Send)
	r := mustAction(t, d.step(local(Event{Kind: ReadReady}, ch)), ReadLocal)
	d.step(local(Event{Kind: LocalData, Data: []byte{'D'}}, r))
	for i := 0; i < 1024; i++ {
		if send.Data[0] == 2 {
			if !bytes.Equal(send.Data, []byte{2, ch.Channel, 1, 0, 'D'}) {
				t.Fatalf("DATA=%x", send.Data)
			}
			return
		}
		if send.Data[0] == 6 {
			w = mustAction(t, d.frame(Frame{DataCommand, ch.Channel, bytes.Repeat([]byte{'a'}, 101)}), WriteLocal)
		} else {
			d.step(local(Event{Kind: LocalWritten, Count: 101}, w))
		}
		send = mustAction(t, d.step(Event{Kind: Sent, Token: send.Token, Count: len(send.Data)}), Send)
	}
	t.Fatalf("queued DATA starved by 1024 accepted flow controls: next=%x usage=%+v", send.Data, d.m.Usage())
}

func TestWakeBehindZeroAcceptedPause(t *testing.T) {
	cfg := DefaultConfig()
	cfg.HighWater = 100
	d := activeDriver(t, cfg, false)
	ch := d.open(445)
	d.auto = false
	out := d.frame(Frame{DataCommand, ch.Channel, bytes.Repeat([]byte{'b'}, MaxData)})
	pause := mustAction(t, out, Send)
	w := mustAction(t, out, WriteLocal)
	d.step(Event{Kind: Sent, Token: pause.Token, Count: 0})
	d.frame(Frame{DataCommand, ch.Channel, bytes.Repeat([]byte{'b'}, MaxData)})
	d.frame(Frame{DataCommand, ch.Channel, bytes.Repeat([]byte{'b'}, MaxData)})
	w = mustAction(t, d.step(local(Event{Kind: LocalWritten, Count: MaxData}, w)), WriteLocal)
	d.step(local(Event{Kind: LocalWritten, Count: 5}, w))
	pause = mustAction(t, d.step(Event{Kind: TransportWritable}), Send)
	if !bytes.Equal(pause.Data, []byte{5, ch.Channel, 0, 0}) {
		t.Fatalf("PAUSE retry=%x", pause.Data)
	}
	out = d.step(Event{Kind: Sent, Token: pause.Token, Count: 4})
	wake, ok := find(out, Send)
	if !ok || !bytes.Equal(wake.Data, []byte{7, ch.Channel, 0, 0}) {
		t.Fatalf("WAKE lost behind zero-accepted PAUSE: Send=%v data=%x queued=%d", ok, wake.Data, d.m.Channel(ch.Channel).Queued)
	}
}

func TestWakeDefaultThreshold(t *testing.T) {
	cfg := DefaultConfig()
	cfg.HighWater = 4 << 20 // Same selected runtime default, explicit for pre-fix control.
	d := activeDriver(t, cfg, false)
	ch := d.open(445)
	d.auto = false
	var pause, w Action
	for left := cfg.HighWater + 2*MaxData; left > 0; {
		n := min(left, MaxData)
		out := d.frame(Frame{DataCommand, ch.Channel, bytes.Repeat([]byte{'b'}, n)})
		left -= n
		if a, ok := find(out, Send); ok {
			pause = a
		}
		if a, ok := find(out, WriteLocal); ok {
			w = a
		}
	}
	if !bytes.Equal(pause.Data, []byte{5, ch.Channel, 0, 0}) {
		t.Fatalf("PAUSE=%x", pause.Data)
	}
	d.step(Event{Kind: Sent, Token: pause.Token, Count: 0})
	w = mustAction(t, d.step(local(Event{Kind: LocalWritten, Count: MaxData}, w)), WriteLocal)
	d.step(local(Event{Kind: LocalWritten, Count: 5}, w))
	pause = mustAction(t, d.step(Event{Kind: TransportWritable}), Send)
	out := d.step(Event{Kind: Sent, Token: pause.Token, Count: 4})
	wake, ok := find(out, Send)
	if !ok || !bytes.Equal(wake.Data, []byte{7, ch.Channel, 0, 0}) {
		t.Fatalf("default 4MiB WAKE lost: Send=%v data=%x queued=%d", ok, wake.Data, d.m.Channel(ch.Channel).Queued)
	}
}
